/**
 * Utility functions for lookup and filtering
 */
export function getConditionById(id: string): Condition | undefined {
  return CONDITIONS.find(c => c.id === id)
}

export function getLookalikeConditions(condition: Condition): Condition[] {
  return condition.lookalikes
    .map(lookalikeId => CONDITIONS.find(c => c.id === lookalikeId))
    .filter((c): c is Condition => Boolean(c))
}

export function searchConditions(query: string): Condition[] {
  const q = query.trim().toLowerCase()
  if (!q) return CONDITIONS

  return CONDITIONS.filter(c => {
    return (
      c.name.toLowerCase().includes(q) ||
      c.aliases.some(a => a.toLowerCase().includes(q)) ||
      c.description.toLowerCase().includes(q) ||
      c.typicalAppearance.some(app => app.toLowerCase().includes(q)) ||
      c.commonLocations.some(loc => loc.toLowerCase().includes(q)) ||
      c.category.toLowerCase().includes(q) ||
      (c.icd10 && c.icd10.toLowerCase().includes(q))
    )
  })
}
